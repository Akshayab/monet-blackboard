function wide(cp: number): boolean {
  // CJK, Hangul, fullwidth forms and emoji are roughly square.
  return (
    (cp >= 0x1100 && cp <= 0x11ff) ||
    (cp >= 0x2e80 && cp <= 0xa4cf) ||
    (cp >= 0xac00 && cp <= 0xd7a3) ||
    (cp >= 0xf900 && cp <= 0xfaff) ||
    (cp >= 0xfe30 && cp <= 0xfe4f) ||
    (cp >= 0xff00 && cp <= 0xff60) ||
    cp >= 0x1f000
  );
}

/** Width of one line of text in em, for the given Excalidraw font family id (5 hand-drawn, 6 normal, 8 mono). */
/**
 * Characters wider than Comic Shanns' 0.55em cell. Most aren't in the font, so browsers draw them with a fallback
 * font whose width varies by machine; these are the widest seen in Chromium, rounded up.
 */
const COMIC_SHANNS_EXTRA: Record<string, number> = { "©": 86, "®": 86, "™": 86, "✓": 86, "✔": 86, "★": 92, "☆": 92, "♥": 92, "≠": 62, ß: 66, ñ: 61 };

function comicShannsWidth(line: string): number {
  let w = 0;
  for (const ch of line) {
    const cp = ch.codePointAt(0)!;
    if (cp >= 32 && cp < 127) w += 55;
    else if (COMIC_SHANNS_EXTRA[ch] !== undefined) w += COMIC_SHANNS_EXTRA[ch]!;
    else w += wide(cp) ? 105 : 62;
  }
  return w / 100;
}

export function lineWidthEm(line: string, fontFamily = 6): number {
  if (fontFamily === 8) return comicShannsWidth(line);
  const ascii = fontFamily === 5 ? EXCALIFONT_ASCII : NUNITO_ASCII;
  const extra = fontFamily === 5 ? EXCALIFONT_EXTRA : NUNITO_EXTRA;
  let w = 0;
  for (const ch of line) {
    const cp = ch.codePointAt(0)!;
    if (cp >= 32 && cp < 127) w += ascii[cp - 32]!;
    else if (extra[ch] !== undefined) w += extra[ch]!;
    else w += wide(cp) ? 105 : 90;
  }
  return w / 100;
}
